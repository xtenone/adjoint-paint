#!/usr/bin/env python3
"""Write a blockMeshDict for a round pipe with a 90 degree bend.

O-grid cross-section (centre square + 4 outer blocks), swept along:
straight inlet (along +x) -> bend in the x-y plane -> straight outlet (along +y).
Dimensions in mm; the dict scales to metres.

Usage: make_pipe_mesh.py <output blockMeshDict>
"""
import math
import sys

# Geometry [mm]
D = 10.0            # pipe diameter
R = 15.0            # bend radius (centreline)
L_IN = 30.0         # straight length before the bend
L_OUT = 50.0        # straight length after the bend
N_BEND_SECTIONS = 3 # bend split into equal arcs (one block ring each)

# Resolution
N_SQ = 10           # cells along a side of the centre square (and around each quarter)
N_RAD = 8           # cells from square to wall
SQ_FRAC = 0.4       # half-width of centre square relative to the radius
RAD_GRADING = 0.5   # last/first radial cell size (finer at the wall)
N_IN = 20
N_BEND = 7          # per bend section
N_OUT = 30

r = D / 2
s = SQ_FRAC * r

def frame(theta):
    """Centre point and in-plane normal of the bend cross-section at angle theta."""
    c = (R * math.sin(theta), R * (1 - math.cos(theta)), 0.0)
    n = (-math.sin(theta), math.cos(theta), 0.0)
    return c, n

def section_points(c, n):
    """8 points: inner square corners 0-3, outer circle points 4-7 (ccw seen along flow)."""
    z = (0.0, 0.0, 1.0)
    phis = [-45, 45, 135, 225]
    inner = [(math.copysign(s, math.cos(math.radians(p))),
              math.copysign(s, math.sin(math.radians(p)))) for p in phis]
    outer = [(r * math.cos(math.radians(p)), r * math.sin(math.radians(p))) for p in phis]
    return [tuple(c[i] + a * n[i] + b * z[i] for i in range(3)) for a, b in inner + outer]

def arc_mid(c, n, phi_deg):
    z = (0.0, 0.0, 1.0)
    a, b = r * math.cos(math.radians(phi_deg)), r * math.sin(math.radians(phi_deg))
    return tuple(c[i] + a * n[i] + b * z[i] for i in range(3))

# Stations along the pipe: (centre, normal, kind of the segment that ends here)
stations = []
c0, n0 = frame(0.0)
stations.append(((c0[0] - L_IN, c0[1], c0[2]), n0))
stations.append((c0, n0))
for k in range(1, N_BEND_SECTIONS + 1):
    stations.append(frame(math.pi / 2 * k / N_BEND_SECTIONS))
c_end, n_end = frame(math.pi / 2)
stations.append(((c_end[0], c_end[1] + L_OUT, c_end[2]), n_end))

# Segment i runs from station i to i+1
segments = ["in"] + ["bend"] * N_BEND_SECTIONS + ["out"]
cells_axial = {"in": N_IN, "bend": N_BEND, "out": N_OUT}
wall_patch = {"in": "wallIn", "bend": "bend", "out": "wallOut"}

vertices = []
for c, n in stations:
    vertices += section_points(c, n)

def v(station, local):
    return 8 * station + local

blocks, edges = [], []
faces = {"inlet": [], "outlet": [], "wallIn": [], "bend": [], "wallOut": []}

for i, kind in enumerate(segments):
    a, b = i, i + 1
    nax = cells_axial[kind]
    # centre block
    blocks.append(([v(a, 0), v(a, 1), v(a, 2), v(a, 3), v(b, 0), v(b, 1), v(b, 2), v(b, 3)],
                   (N_SQ, N_SQ, nax), (1, 1, 1)))
    # outer blocks
    for j in range(4):
        jn = (j + 1) % 4
        blocks.append(([v(a, j), v(a, 4 + j), v(a, 4 + jn), v(a, jn),
                        v(b, j), v(b, 4 + j), v(b, 4 + jn), v(b, jn)],
                       (N_RAD, N_SQ, nax), (RAD_GRADING, 1, 1)))
        faces[wall_patch[kind]].append([v(a, 4 + j), v(a, 4 + jn), v(b, 4 + jn), v(b, 4 + j)])
    # axial arcs along the bend
    if kind == "bend":
        th_a = math.pi / 2 * (a - 1) / N_BEND_SECTIONS
        th_b = math.pi / 2 * (b - 1) / N_BEND_SECTIONS
        cm, nm = frame(0.5 * (th_a + th_b))
        mids = section_points(cm, nm)
        for local in range(8):
            edges.append((v(a, local), v(b, local), mids[local]))

# circumferential arcs at every station
for st, (c, n) in enumerate(stations):
    for j, phi in enumerate([-45, 45, 135, 225]):
        jn = (j + 1) % 4
        edges.append((v(st, 4 + j), v(st, 4 + jn), arc_mid(c, n, phi + 45)))

# inlet / outlet faces (normals pointing out of the domain)
last = len(stations) - 1
faces["inlet"].append([v(0, 0), v(0, 3), v(0, 2), v(0, 1)])
faces["outlet"].append([v(last, 0), v(last, 1), v(last, 2), v(last, 3)])
for j in range(4):
    jn = (j + 1) % 4
    faces["inlet"].append([v(0, j), v(0, jn), v(0, 4 + jn), v(0, 4 + j)])
    faces["outlet"].append([v(last, j), v(last, 4 + j), v(last, 4 + jn), v(last, jn)])

def fmt(p):
    return "(%.6f %.6f %.6f)" % p

out = []
out.append("""FoamFile
{
    version     2.0;
    format      ascii;
    class       dictionary;
    object      blockMeshDict;
}
// Generated by tools/make_pipe_mesh.py

scale 0.001;
""")
out.append("vertices\n(\n" + "".join("    %s // %d\n" % (fmt(p), i) for i, p in enumerate(vertices)) + ");\n")
out.append("blocks\n(\n" + "".join(
    "    hex (%s) (%d %d %d) simpleGrading (%g %g %g)\n" % ((" ".join(map(str, vs)),) + cells + grading)
    for vs, cells, grading in blocks) + ");\n")
out.append("edges\n(\n" + "".join("    arc %d %d %s\n" % (p, q, fmt(m)) for p, q, m in edges) + ");\n")
types = {"inlet": "patch", "outlet": "patch", "wallIn": "wall", "bend": "wall", "wallOut": "wall"}
out.append("boundary\n(\n")
for name, fl in faces.items():
    out.append("    %s\n    {\n        type %s;\n        faces\n        (\n" % (name, types[name]))
    out += ["            (%s)\n" % " ".join(map(str, f)) for f in fl]
    out.append("        );\n    }\n")
out.append(");\n")

with open(sys.argv[1], "w") as fh:
    fh.write("".join(out))
